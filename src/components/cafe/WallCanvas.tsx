import type { ReactNode } from "react";
import { canvasWidth, LOOP_MS, SCREENS, sliceOffset } from "@/lib/cafe/wall";

/**
 * نافذةُ شاشةٍ واحدة على لوحةٍ واحدة.
 *
 * اللوحة عرضها `400vw` ويُرسَم عليها التصميم كاملاً مرّةً واحدة. وكل شاشة
 * تُزيح اللوحة بمقدار ربعٍ وتقصّ الباقي — فالعنصر الذي يعبر من الأولى إلى
 * الرابعة **يعبر داخل اللوحة نفسها**، لا أربع نسخٍ متّفقة على التظاهر.
 *
 * وبوحدات المنفذ لا بالبكسل: تلفزيون المحل يقرأ منفذه نحو ٩٦٠ بكسل على لوحة
 * 1080p — التلفزيونات تضاعف بكسلاتها — فأي رقمٍ مطلق يكسر نصف الأجهزة، و`vw`
 * تعني «عرض هذه الشاشة» أياً كان.
 *
 * والتزامن كلّه في سطرٍ واحد هنا: `animationDelay` سالبٌ يحسبه **الخادم** من
 * ساعته، فتقفز الشاشات الأربع إلى اللحظة نفسها من الدورة نفسها. ساعةُ الجهاز
 * لا تدخل الحساب — وهذا ما يجعل أربعة أجهزة منفصلة ممكنة أصلاً.
 */
export function WallCanvas({
  screen,
  phaseMs,
  bezel,
  preview = false,
  children,
}: {
  screen: number;
  /** أين نحن من الدورة، بحساب الخادم */
  phaseMs: number;
  /** عرض حافّة الإطار بالبكسل — صفرٌ = لا تعويض */
  bezel: number;
  /**
   * عرضُ الجدار كلّه مصغَّراً على شاشةٍ واحدة — للاطّلاع لا للتشغيل.
   *
   * أربع نوافذ متصفّح لا تُريك التكوين: العين لا تجمع ما تفرّق على أربع
   * شاشات. وهذا يعرض اللوحة كاملةً بربع حجمها، فيُحكَم على التصميم قبل أن
   * يُعلَّق على الحائط.
   */
  preview?: boolean;
  children: ReactNode;
}) {
  return (
    // أنماطٌ مضمّنة لا أصناف: مرّتين من قبل أعاد مُصغِّر CSS كتابة اختيارٍ
    // مقصود لمتصفّحٍ قديم — طوى الإزاحات الأربع إلى `inset` التي لا يعرفها
    // Chromium ٨٧. والمضمّن في HTML لا يمرّ على مُصغِّر
    <div
      dir="rtl"
      style={{
        position: "fixed",
        top: 0,
        right: 0,
        bottom: 0,
        left: 0,
        overflow: "hidden",
        // برتقالي الهوية. كانت داكنة فاستُبدلت: الأسود ليس من هوية المحطة،
        // و#ff6b00 هو اللون المطبوع على العلب نفسها (--primary)
        background: "#ff6b00",
        cursor: "none",
      }}
    >
      <div
        className="wall-canvas"
        style={
          {
            position: "absolute",
            top: preview ? "50%" : 0,
            left: preview ? 0 : sliceOffset(screen, bezel),
            width: canvasWidth(bezel),
            /*
             * `100vh` لا `100%` — وهذا هو العطل الذي أخفى الجدار كلّه.
             *
             * الأب مثبَّتٌ بإزاحاته الأربع (top/right/bottom/left) ولا يحمل
             * خاصّية `height`. والنسبة المئوية تُحسب من **خاصّية** الأب لا من
             * حجمه المرسوم، فمتصفّح التلفزيون قرأ `height: 100%` من `auto`
             * وأعطى اللوحة **ارتفاع صفر**. عرضها صحيح (‎5120px‎ صريحة) وموضعها
             * صحيح (‎-3840px‎)، فقرأت المسطرة الاثنين سليمين — ولا شيء يُرسم،
             * لأن كل المشاهد داخلها بارتفاع صفر.
             *
             * ودليله في المسطرة نفسها: `vis 3 · here 1`. ثلاثة عناصر ظاهرة،
             * وواحدٌ فقط يقع داخل الشاشة — وهو الشريط وحده، لأن ارتفاعه
             * بـ`vh` فلا يعتمد على الأب. والباقي بارتفاع صفرٍ خارج الحساب.
             *
             * ووحدات المنفذ لا تسأل أباها عن شيء.
             */
            height: "100vh",
            // في العرض المصغَّر: اللوحة كلّها بربع حجمها، ممركزةً رأسياً.
            // ونقطة التحجيم في اليسار الأعلى فتُقرأ الإزاحة من حافّة الشاشة.
            ...(preview
              ? { transform: `scale(${1 / SCREENS}) translateY(-50%)`, transformOrigin: "0 0" }
              : {}),
            // الطور يُورَّث إلى كل متحرّك عبر متغيّر مخصّص: يُكتب هنا مرّة،
            // ويقرؤه كل عنصر. سالبٌ فيقفز بالدورة إلى موضعها بدل أن تبدأ من
            // رأسها — وبه وحده تتّفق أربع شاشاتٍ على أربعة أجهزة
            ["--wall-phase"]: `-${phaseMs}ms`,
          } as React.CSSProperties
        }
      >
        {children}
      {/*
        حارسان: واحدٌ يُصحّح التزامن، وآخرٌ يُجدّد الصفحة.

        **التصحيح يقيس الحركة ولا يحاكيها.** كان يحسب طوره بساعةٍ موازية:
        «الطور المحقون + ما مضى منذ أن عمل هذا السطر». والحركة في الحقيقة تبدأ
        حين يُرسم العنصر أوّل مرّة — لا حين يعمل السطر. وبينهما على تلفزيونٍ
        بطيء ثانيةٌ أو ثلاث، تختلف من جهازٍ إلى جهاز.

        فكانت الشاشة البطيئة تنحرف بمقدار بطئها، **والمصحّح لا يرى انحرافها**
        لأنه يسأل ساعته لا الشاشة: يجد نفسه مضبوطاً فلا يصحّح شيئاً. وهكذا
        يبقى الانحراف إلى الأبد، وتقف شاشةٌ واحدة متأخّرةً عن أخواتها.

        والآن يُقرأ الطور من الحركة نفسها (`getAnimations`) — فما يُقاس هو ما
        يُرى، ويُصحَّح إلى لحظة الخادم في خطوةٍ واحدة. وما دون ربع ثانية
        يُترك: العين لا تراه، وتحريك التأخير يقفز بالمشهد.
      */}
      <script
        dangerouslySetInnerHTML={{
          __html: `try{
            var LOOP = ${LOOP_MS}, cv = document.currentScript.parentNode;
            // مقدار التأخير السالب المكتوب على اللوحة. تحريكه بمقدار د يحرّك
            // الطور بمقدار د — وهذا كل ما يفعله التصحيح
            var base = ${phaseMs}, baseAt = Date.now();

            // الطور كما تراه الحركة فعلاً. currentTime يتضمّن التأخير
            // السالب، فباقي قسمته على الدورة هو موضعنا منها بالضبط
            function phaseNow(){
              try{
                var el = cv.querySelector('.wall-anim');
                if (el && el.getAnimations) {
                  var a = el.getAnimations()[0];
                  // الحركة لم تنطلق بعد — فلا يُصحَّح على تخمين. وهذا ما كان
                  // يقع: أوّل مزامنةٍ تعمل والصفحة ما زالت تُحلَّل، فتقارن
                  // الخادمَ بساعةٍ موازية فتجدهما متّفقين وتمضي، والحركة بعدُ
                  // لم تبدأ. فتبقى الشاشة متأخّرةً بقدر ما تأخّر انطلاقها
                  if (!a || a.currentTime == null) return null;
                  return ((a.currentTime % LOOP) + LOOP) % LOOP;
                }
              }catch(x){}
              // متصفّحٌ لا يعرف getAnimations: تُستعمل الساعة الموازية كما كانت
              return ((base + (Date.now() - baseAt)) % LOOP + LOOP) % LOOP;
            }

            function sync(){
              var t0 = Date.now();
              fetch('/api/wall/now', { cache: 'no-store' })
                .then(function(r){ return r.json(); })
                .then(function(j){
                  var now = Date.now();
                  var want = (j.t + (now - t0) / 2) % LOOP;
                  var have = phaseNow();
                  if (have !== null) {
                    // الفارق يُقاس على الدائرة: ١٧٩ثا و١ثا متجاورتان لا متباعدتان
                    var d = ((want - have) % LOOP + LOOP + LOOP / 2) % LOOP - LOOP / 2;
                    if (Math.abs(d) > 250) {
                      base = ((base + d) % LOOP + LOOP) % LOOP;
                      cv.style.setProperty('--wall-phase', '-' + Math.round(base) + 'ms');
                    }
                  }
                  plan(j.t);
                })
                .catch(function(){});
            }

            /*
             * التجديد على رأس الساعة — بساعة الخادم لا بمؤقّت كل شاشة.
             *
             * كان كل جهازٍ يجدّد نفسه بعد عشر دقائق من **فتحه هو**. وأوقات
             * الفتح مختلفة، فكانت شاشةٌ تُعيد التحميل بينما تمضي الثلاث:
             * تسودّ وحدها، ثم تعود من رأس المشهد لا من موضعه. وهو بالضبط ما
             * رآه المالك على الثالثة.
             *
             * والآن اللحظة محسوبةٌ من ساعة الخادم، فهي نفسها على الأربع:
             * يُجدّدن معاً في الثانية نفسها، ويعدن معاً. ومرّةً في الساعة لا
             * ستّاً — والغرض منها التقاط نشرٍ جديد والخروج من أي حالةٍ عَلِقت.
             */
            var planned = false;
            function plan(serverT){
              if (planned) return;
              planned = true;
              var wait = 3600000 - (serverT % 3600000);
              setTimeout(function(){
                var u = location.pathname + '?r=' + Date.now();
                if (location.search.indexOf('d') > -1) u += '&d=1';
                location.href = u;
              }, wait);
            }

            // إلّا حين تُجمَّد اللوحة بالمعامل t للفحص: المزامن يجرّها إلى الآن
            // فيضيع التجميد، ويصير إثبات الاتّصال بين الشاشات مستحيلاً
            // مزامناتٌ مبكّرة ثم كل دقيقتين: أوّل قياسٍ صحيح لا يكون إلا بعد
            // أن تنطلق الحركة، وذلك يتأخّر على جهازٍ بطيء. فتُعاد المحاولة
            // بعد ثانيتين وثمانٍ وعشرين — فتستقيم الشاشة في ثوانٍ لا في دقيقتين
            if (location.search.indexOf('t=') < 0) {
              sync();
              setTimeout(sync, 2000);
              setTimeout(sync, 8000);
              setTimeout(sync, 20000);
              setInterval(sync, 120000);
            }
          }catch(e){}`,
        }}
      />
      </div>
    </div>
  );
}
