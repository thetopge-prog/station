import type { ReactNode } from "react";
import { canvasWidth, SCREENS, sliceOffset } from "@/lib/cafe/wall";

/**
 * نافذةُ شاشةٍ واحدة على لوحةٍ واحدة.
 *
 * اللوحة عرضها `400vw` ويُرسَم عليها التصميم كاملاً مرّةً واحدة. وكل شاشة
 * تُزيح اللوحة بمقدار ربعٍ وتقصّ الباقي — فالعنصر الذي يعبر من الأولى إلى
 * الرابعة **يعبر داخل اللوحة نفسها**، لا أربع نسخٍ متّفقة على التظاهر.
 *
 * وبوحدات المنفذ لا بالبكسل: تلفزيون المحل يقرأ منفذه نحو ٩٦٠ بكسل على لوحة
 * 1080p — التلفزيونات تضاعف بكسلاتها — فأي رقمٍ مطلق يكسر نصف الأجهزة، و`vw`
 * تعني «عرض هذه الشاشة» أياً كان.
 *
 * والتزامن كلّه في سطرٍ واحد هنا: `animationDelay` سالبٌ يحسبه **الخادم** من
 * ساعته، فتقفز الشاشات الأربع إلى اللحظة نفسها من الدورة نفسها. ساعةُ الجهاز
 * لا تدخل الحساب — وهذا ما يجعل أربعة أجهزة منفصلة ممكنة أصلاً.
 */
export function WallCanvas({
  screen,
  phaseMs,
  bezel,
  preview = false,
  children,
}: {
  screen: number;
  /** أين نحن من الدورة، بحساب الخادم */
  phaseMs: number;
  /** عرض حافّة الإطار بالبكسل — صفرٌ = لا تعويض */
  bezel: number;
  /**
   * عرضُ الجدار كلّه مصغَّراً على شاشةٍ واحدة — للاطّلاع لا للتشغيل.
   *
   * أربع نوافذ متصفّح لا تُريك التكوين: العين لا تجمع ما تفرّق على أربع
   * شاشات. وهذا يعرض اللوحة كاملةً بربع حجمها، فيُحكَم على التصميم قبل أن
   * يُعلَّق على الحائط.
   */
  preview?: boolean;
  children: ReactNode;
}) {
  return (
    // أنماطٌ مضمّنة لا أصناف: مرّتين من قبل أعاد مُصغِّر CSS كتابة اختيارٍ
    // مقصود لمتصفّحٍ قديم — طوى الإزاحات الأربع إلى `inset` التي لا يعرفها
    // Chromium ٨٧. والمضمّن في HTML لا يمرّ على مُصغِّر
    <div
      dir="rtl"
      style={{
        position: "fixed",
        top: 0,
        right: 0,
        bottom: 0,
        left: 0,
        overflow: "hidden",
        // برتقالي الهوية. كانت داكنة فاستُبدلت: الأسود ليس من هوية المحطة،
        // و#ff6b00 هو اللون المطبوع على العلب نفسها (--primary)
        background: "#ff6b00",
        cursor: "none",
      }}
    >
      <div
        className="wall-canvas"
        style={
          {
            position: "absolute",
            top: preview ? "50%" : 0,
            left: preview ? 0 : sliceOffset(screen, bezel),
            width: canvasWidth(bezel),
            /*
             * `100vh` لا `100%` — وهذا هو العطل الذي أخفى الجدار كلّه.
             *
             * الأب مثبَّتٌ بإزاحاته الأربع (top/right/bottom/left) ولا يحمل
             * خاصّية `height`. والنسبة المئوية تُحسب من **خاصّية** الأب لا من
             * حجمه المرسوم، فمتصفّح التلفزيون قرأ `height: 100%` من `auto`
             * وأعطى اللوحة **ارتفاع صفر**. عرضها صحيح (‎5120px‎ صريحة) وموضعها
             * صحيح (‎-3840px‎)، فقرأت المسطرة الاثنين سليمين — ولا شيء يُرسم،
             * لأن كل المشاهد داخلها بارتفاع صفر.
             *
             * ودليله في المسطرة نفسها: `vis 3 · here 1`. ثلاثة عناصر ظاهرة،
             * وواحدٌ فقط يقع داخل الشاشة — وهو الشريط وحده، لأن ارتفاعه
             * بـ`vh` فلا يعتمد على الأب. والباقي بارتفاع صفرٍ خارج الحساب.
             *
             * ووحدات المنفذ لا تسأل أباها عن شيء.
             */
            height: "100vh",
            // في العرض المصغَّر: اللوحة كلّها بربع حجمها، ممركزةً رأسياً.
            // ونقطة التحجيم في اليسار الأعلى فتُقرأ الإزاحة من حافّة الشاشة.
            ...(preview
              ? { transform: `scale(${1 / SCREENS}) translateY(-50%)`, transformOrigin: "0 0" }
              : {}),
            // الطور يُورَّث إلى كل متحرّك عبر متغيّر مخصّص: يُكتب هنا مرّة،
            // ويقرؤه كل عنصر. سالبٌ فيقفز بالدورة إلى موضعها بدل أن تبدأ من
            // رأسها — وبه وحده تتّفق أربع شاشاتٍ على أربعة أجهزة
            ["--wall-phase"]: `-${phaseMs}ms`,
          } as React.CSSProperties
        }
      >
        {children}
      {/* حارسٌ يُعيد التحميل من داخل الصفحة.
          ترويسة `Refresh` وحدها لم تكفِ: شاشةٌ على الجدار بقيت على نفس الطور
          الذي فُتحت عليه بعد أن مضى وقتٌ طويل — إمّا أن المتصفّح أهمل
          الترويسة، وإمّا أنه جمّد الصفحة كلّها. والمؤقّت يُعلَّق على صفحةٍ لا
          يلمسها أحد، فهذا لا يغني عن الترويسة بل يسندها: أيّهما عمل كفى. */}
      <script
        dangerouslySetInnerHTML={{
          __html: `try{setTimeout(function(){
            // **عنوانٌ جديد في كل مرّة، لا `+"`reload`"+`.**
            //
            // إعادة التحميل تسأل المتصفّح عن نفس العنوان، ومتصفّح التلفزيون
            // يجيب من خزينه: شاشةٌ بقيت على نفس الطور الذي فُتحت عليه رغم
            // الترويسة ورغم النشر. وكل إصلاحٍ نُشر لم يصل إليها.
            //
            // ورقمُ اللحظة في العنوان يجعله عنواناً لم يره الخزين من قبل،
            // فلا يملك إلّا أن يسأل الخادم.
            var u = location.pathname + '?r=' + Date.now();
            if (location.search.indexOf('debug') > -1) u += '&debug=1';
            location.href = u;
          }, 600000);}catch(e){}`,
        }}
      />
      </div>
    </div>
  );
}
