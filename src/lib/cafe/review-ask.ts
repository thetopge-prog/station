import { BRAND } from "@/lib/brand";

/**
 * رسالة طلب التقييم على خرائط جوجل — نصّاً وتوقيتاً.
 *
 * ملفٌّ نقيّ كـ`wall.ts`: لا شبكة ولا قاعدة ولا React. فيُختبَر بلا بيئة، وهو
 * المكان الوحيد الذي يُكتب فيه النصّ — فتعديل كلمةٍ سطرٌ واحد لا بحثٌ في خمسة
 * ملفّات.
 *
 * ولا حرف «گ» في شيءٍ ممّا هنا: خطّ النظام (Tajawal) لا يحمله، فيستعيره
 * المتصفّح من خطٍّ آخر ويخرج غريباً عن أخواته — وقد شكا المالك منه. وحارسه
 * اختبارٌ يفحص كل نصٍّ يخرج من هذا الملفّ.
 */

/** الرابط كما أعطاه المالك — في `brand.ts` مع بقيّة ما يُعرّف المحل */
export const REVIEW_URL = BRAND.reviewUrl;

/**
 * كم ننتظر بعد «سلّمت» قبل أن نسأل.
 *
 * `handed_at` في التوصيل هي لحظة تسليم الطلب **للسائق** لا للزبون، وبينهما
 * الطريق. فخمس عشرة دقيقةً هناك تصل والزبون ما زال ينتظر على بابه — وهي أسوأ
 * لحظةٍ تُطلب فيها خدمة. ثلاثون تكفي ليأكل.
 *
 * أما الاستلام والسفري والسيارة فالطعام بيده لحظةَ الختم.
 */
export const reviewDelayMs = (channel: string | null): number =>
  (channel === "delivery" ? 30 : 15) * 60_000;

/** هل حان وقت السؤال عن هذا الطلب؟ */
export const reviewDue = (handedAt: string | null, channel: string | null, now = Date.now()): boolean => {
  if (!handedAt) return false;
  const at = Date.parse(handedAt);
  return Number.isFinite(at) && now - at >= reviewDelayMs(channel);
};

/**
 * نصّ الرسالة.
 *
 * والاسم شرطُه أن يكون اسماً: من كتب على واتساب «عاشق ولهان» لا يُنادى به،
 * فالتصفية في `wa-name.ts` وتُطبَّق قبل النداء هنا. وبلا اسمٍ تبدأ بـ«هلا بيك»
 * — تحيّةٌ تامّة لا جملةٌ ناقصة ينقصها اسم.
 *
 * و`focus` اسم القسم الذي تكرّر ثلاث مرّاتٍ من ثلاث. حينها يُسأل عنه بالاسم:
 * السؤال الذي يعرف ما أكلتَه يُجاب، والعامّ يُتجاهل.
 */
export function reviewMessage(input: { name?: string | null; focus?: string | null; url?: string }): string {
  const name = (input.name ?? "").trim();
  const hello = name ? `هلا ${name} 🧡` : "هلا بيك 🧡";
  const focus = (input.focus ?? "").trim();
  const url = input.url ?? REVIEW_URL;

  const opening = focus
    ? [`${hello} شفناك طلبت **${focus}** ثلاث مرّات — شنو رأيك بيه بصراحة؟`, "ورأيك يهمّنا هواي، وإحنا على أبواب رؤية جديدة للمحطة."]
    : [hello, "إحنا على أبواب رؤية جديدة لمطعم المحطة، ورأيك يهمّنا هواي."];

  return [
    ...opening,
    "تاخذ من وقتك دقيقتين وتدخل على الرابط وتكتب عن تجربتك ويانا؟",
    "ويا ريت ترفق صور من الوجبات الي استلمتها 📸",
    url,
    "وبعد ما تقيّم خبّرنا هنا 🙏 وشكراً إلك.",
  ].join("\n");
}
