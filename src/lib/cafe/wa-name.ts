/**
 * الاسم الذي يُنادى به الزبون، أو `null` إن لم يكن اسماً واضحاً.
 *
 * تُؤخذ الكلمة الأولى وحدها: «احمد محمد علي» يُنادى «أحمد»، لا باسمه الثلاثي.
 * والزخرفة تُرفض كما هي — حرفٌ خارج العربية والإنجليزية يعني أن صاحبه اختار
 * شكلاً لا اسماً.
 */
export function customerNameFrom(profileName: string | null | undefined): string | null {
  const raw = (profileName ?? "").trim();
  if (!raw || raw.length > 60) return null;
  // أرقامٌ أو رموزٌ أو زخرفة في أي موضع → ليس اسماً يُنادى به
  if (!/^[ء-يa-zA-Z\s.'-]+$/.test(raw)) return null;

  const first = raw.split(/[\s.'-]+/).filter(Boolean)[0] ?? "";
  if (first.length < 2 || first.length > 15) return null;

  const f = fold(first);
  if (NAMES.has(f) || LATIN_NAMES.has(f)) return first;
  // «عبد الله» و«عبد الرحمن» تُكتبان مفصولتين كثيراً — تُجرَّب الكلمتان معاً
  const two = raw.split(/\s+/).slice(0, 2).join("");
  if (two && NAMES.has(fold(two))) return raw.split(/\s+/).slice(0, 2).join(" ");
  return null;
}
