/**
 * اسم الزبون كما كتبه هو في ملفّه على واتساب — ومتى يُنادى به.
 *
 * واتساب يرسل مع كل رسالة اسم صاحبها كما اختاره لنفسه. أكثره أسماءٌ حقيقية،
 * وبعضه «عاشق ولهان» و«ذيب الصحراء» و«𝓐𝓱𝓶𝓮𝓭 ♥». ومناداة الزبون باسمٍ
 * حقيقي تفتح المحادثة، ومناداته بلقبه تُحرجه أو تُضحك عليه — والثانية أسوأ
 * من ألّا نناديه أصلاً.
 *
 * فالقاعدة هنا **قائمةُ سماح لا قائمةَ منع**: تُقبل الكلمة الأولى إن كانت
 * اسماً معروفاً، ويُصمت عمّا عداه. وقوائم المنع لا تنتهي — كل يومٍ لقبٌ جديد —
 * أما الأسماء فمجموعةٌ محدودة. والخطأ في هذا الاتّجاه كلفته تحيّةٌ عامّة، وفي
 * الاتّجاه الآخر كلفته زبونٌ يُنادى «يا عاشق».
 */

/** طيّ الحرف العربي: الهمزات ألفاً، والتاء المربوطة هاءً، وبلا تشكيل */
function fold(w: string): string {
  return w
    .replace(/[ً-ْـ]/g, "")
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/[ىئ]/g, "ي")
    .replace(/ؤ/g, "و")
    .toLowerCase();
}

