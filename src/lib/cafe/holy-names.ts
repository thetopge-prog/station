/**
 * اسم الزبون على الورق — بلا لفظ الجلالة مكتوباً.
 *
 * الوصل يُرمى. والمالك لا يريد ورقة فيها «الله» أو اسم من أسمائه الحسنى في
 * القمامة. الحلّ الذي طلبه: يبقى الاسم مقروءاً من أول نظرة، لكنّ الكلمة
 * المقدّسة لا تكون مكتوبة كاملة — حرف أو حرفان منها مربّع أسود:
 *   عبد الله    ← عبدا■ـه
 *   عبد الإله   ← عبد ا■لا■ه
 *   عبد الرحمن  ← عبد الر■من
 *
 * المربّع ■ (U+25A0) موجود في Tahoma التي يرسم بها وكيل الطباعة.
 *
 * ما يُمسّ: لفظ الجلالة أينما وقع، و«الإله»، وأي اسم من الأسماء الحسنى جاء بعد
 * «عبد» (منفصلة أو ملتصقة). «كريم» و«رحيم» وحدهما اسمان لأناس ولا يُمسّان.
 */

const SQ = "■";

/** الأسماء الحسنى بلا «ال»، بهمزاتها موحَّدة (أ إ آ ← ا، ؤ ← و، ئ ← ي) */
const NAMES = new Set(
  `رحمن رحيم ملك قدوس سلام مومن مهيمن عزيز جبار متكبر خالق بارئ باري مصور غفار قهار وهاب رزاق فتاح عليم
   قابض باسط خافض رافع معز مذل سميع بصير حكم عدل لطيف خبير حليم عظيم غفور شكور علي كبير حفيظ مقيت حسيب
   جليل كريم رقيب مجيب واسع حكيم ودود مجيد باعث شهيد حق وكيل قوي متين ولي حميد محصي مبدئ مبدي معيد محيي
   مميت حي قيوم واجد ماجد واحد احد صمد قادر مقتدر مقدم موخر اول اخر ظاهر باطن والي متعالي بر تواب منتقم
   عفو روف رووف مالك مقسط جامع غني مغني مانع ضار نافع نور هادي بديع باقي وارث رشيد صبور`
    .split(/\s+/)
    .filter(Boolean),
);

const norm = (w: string) => w.replace(/[أإآ]/g, "ا").replace(/ؤ/g, "و").replace(/ئ/g, "ي").replace(/ـ/g, "");

/** «رحمن» ← «ر■من»: الحرف الثاني وكل ثانٍ بعده مربّع، والأول والأخير يبقيان */
function veil(stem: string): string {
  if (stem.length < 3) return stem[0] + SQ;
  const out = [...stem];
  for (let i = 1; i < out.length - 1; i += 2) out[i] = SQ;
  return out.join("");
}

/** الكلمة بعد «عبد» — بـ«ال» أو بغيرها — إن كانت من الأسماء الحسنى */
function veilAfterAbd(word: string): string {
  const m = word.match(/^(ال)?(.+)$/);
  if (!m) return word;
  const stem = m[2];
  if (!NAMES.has(norm(stem))) return word;
  return (m[1] ?? "") + veil(stem);
}

export function maskHolyNames(name: string | null | undefined): string | null {
  if (!name) return null;
  let s = name;
  // لفظ الجلالة و«الإله» أينما وقعا: عبدالله، فتح الله، الإله
  s = s.replace(/الله/g, `ا${SQ}ـه`).replace(/ال[إا]له/g, `ا${SQ}لا${SQ}ه`);
  // «عبد الرحمن» و«عبدالرحمن»
  s = s.replace(/(^|\s)عبد\s+(\S+)/g, (_, pre: string, w: string) => `${pre}عبد ${veilAfterAbd(w)}`);
  s = s.replace(/(^|\s)عبد(ال\S+)/g, (_, pre: string, w: string) => `${pre}عبد${veilAfterAbd(w)}`);
  return s;
}
