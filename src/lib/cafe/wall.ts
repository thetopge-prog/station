/** بداية كل مشهد من أول الدورة — يُشتقّ ولا يُكتب بيد */
export function sceneStarts(scenes: Scene[] = SCENES): Record<string, number> {
  const out: Record<string, number> = {};
  let at = 0;
  for (const s of scenes) {
    out[s.id] = at;
    at += s.ms;
  }
  return out;
}

/**
 * نافذة المشهد كنسبة مئوية من الدورة.
 *
 * `@keyframes` تُوقَّت بالنسب لا بالمللي، ولا تقبل متغيّرات — فالنسب تُكتب
 * بيدٍ في ملفّ الأنماط. وهذا بابُ انحرافٍ صامت: تُطال مدّة مشهدٍ هنا فتبقى
 * نسبته هناك، فيتداخل مشهدان ولا يخبر أحدٌ أحداً.
 *
 * فتُشتقّ النسب من الجدول نفسه، ويقرأ اختبارٌ ملفَّ الأنماط ويطابق ما فيه
 * بما هنا. (نفس حيلة `nav.test.ts` حين يقرأ مصدر الصفحات ليتأكّد من حارسها.)
 */
export function scenePct(id: string, scenes: Scene[] = SCENES): { from: number; to: number } {
  const starts = sceneStarts(scenes);
  const s = scenes.find((x) => x.id === id);
  if (!s) throw new Error(`لا مشهد باسم ${id}`);
  const total = scenesTotal(scenes);
  const pct = (ms: number) => Math.round((ms / total) * 10_000) / 100;
  return { from: pct(starts[id]), to: pct(starts[id] + s.ms) };
}

/** مجموع المُدَد — يجب أن يساوي الدورة */
export const scenesTotal = (scenes: Scene[] = SCENES): number => scenes.reduce((t, s) => t + s.ms, 0);

/** أي مشهدٍ نحن فيه عند هذا الطور — للفحص والتصوير لا للعرض */
export function sceneAt(phaseMs: number, scenes: Scene[] = SCENES): Scene {
  let at = 0;
  for (const s of scenes) {
    at += s.ms;
    if (phaseMs < at) return s;
  }
  return scenes[scenes.length - 1];
}

