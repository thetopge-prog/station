/**
 * جدار «المحطة» — الحساب الصافي للوحة البانورامية.
 *
 * أربع شاشات متجاورة تبدو لوحةً واحدة. والفكرة كلّها في سطر: **التصميم يُبنى
 * مرّة على مساحة `400vw`، وكل شاشة تُظهر ربعها**. فالعنصر الذي يعبر من الشاشة
 * الأولى إلى الرابعة يعبر داخل اللوحة نفسها — لا نسخة له في كل صفحة، ولا
 * تسليمَ عند الحدود.
 *
 * وهذا الملف بلا React وبلا متصفّح: هو ما يُختبر، والباقي ترميزٌ للتصميم.
 */

/** عدد الشاشات. اللوحة `SCREENS × 100vw` عرضاً */
export const SCREENS = 4;

/**
 * طول الدورة الكاملة.
 *
 * تُقرأ في مكانين: الخادم يحسب منها الطور، وملفّ الأنماط يوقّت بها كل مشهد.
 * فإن تغيّرت هنا ولم تتغيّر هناك انفرط التسلسل — ولذلك يحرسها اختبار يجمع
 * مُدَد المشاهد ويطابقها بها.
 */
export const LOOP_MS = 140_000;

/** رقم الشاشة كما يأتي من المسار — وهو مدخل من المستخدم فيُفحَص */
export function screenIndex(raw: string | undefined): number | null {
  if (!/^[1-4]$/.test(raw ?? "")) return null;
  return Number(raw);
}

/**
 * طور الدورة: أين نحن منها الآن.
 *
 * يُحسب على **الخادم** لا على الجهاز، وهذا هو بيت القصيد: أربعة أجهزة منفصلة
 * لها أربع ساعات تنحرف، فلو حسب كلٌّ منها طوره لسبقت شاشةٌ أختها بثوانٍ.
 * ساعةُ الخادم واحدة، فتقفز الشاشات الأربع إلى اللحظة نفسها مهما تفرّقت
 * أوقات فتحها.
 */
export const loopPhase = (nowMs: number): number => ((nowMs % LOOP_MS) + LOOP_MS) % LOOP_MS;

/**
 * عرض اللوحة، متضمّناً فجوات الإطارات.
 *
 * بلا تعويض هي `400vw` ببساطة. ومع تعويضٍ تتّسع بثلاث فجوات — لأن بين أربع
 * شاشات ثلاثة حدود — فيصير في اللوحة «مساحةٌ مخفيّة» تقع تحت الإطارات تماماً
 * كما في جدران الفيديو الحقيقية.
 */
export const canvasWidth = (bezel = 0): string =>
  bezel > 0 ? `calc(${SCREENS * 100}vw + ${(SCREENS - 1) * bezel}px)` : `${SCREENS * 100}vw`;

/**
 * الإزاحة التي تُظهر نافذة الشاشة رقم `n`.
 *
 * بوحدات المنفذ لا بالبكسل: تلفزيون المحل يقرأ منفذه نحو ٩٦٠ بكسل على لوحة
 * 1080p (التلفزيونات تضاعف بكسلاتها)، فأي رقمٍ مطلق يكسر التصميم على نصف
 * الأجهزة. و`100vw` تعني «عرض هذه الشاشة» أياً كان.
 *
 * ومع تعويض الحافّة تُزاح الشاشة بعرضها **زائد فجوة**، فما يقع تحت الإطار
 * البلاستيكي لا يُرسَم على أيٍّ من الشاشتين — فيمرّ البركر خلف الحافّة ويخرج
 * من الجهة الأخرى في موضعه الصحيح، بدل أن يقفز.
 *
 * والإزاحة من اليسار لا من اليمين: الشاشة ١ هي أقصى اليسار (`x = 0 → W`) كما
 * في مواصفة المالك، وهي كذلك ترتيبُ تعليقها على الجدار. والمحتوى داخل اللوحة
 * يبقى عربياً يُقرأ من اليمين — الاتجاهان مستقلّان.
 */
export const sliceOffset = (n: number, bezel = 0): string =>
  bezel > 0 ? `calc(-${(n - 1) * 100}vw - ${(n - 1) * bezel}px)` : `-${(n - 1) * 100}vw`;

/**
 * تعويض حافّة الإطار.
 *
 * الشاشات الأربع بينها حوافّ بلاستيكية، والبركر العابر يقفز عندها لأن جزءاً
 * منه يقع «تحت» الحافّة ولا يُرسَم. فتُوسَّع شريحة كل شاشة بمقدار الحافّة
 * ويُقتطع ما تحتها — كما تفعل جدران الفيديو الحقيقية. صفرٌ = لا تعويض.
 *
 * يُضبط على الجدار بـ`?bezel=24` بلا إعادة نشر، لأن الرقم لا يُعرف إلا
 * بالوقوف أمام الشاشات.
 */
export function bezelPx(raw: string | string[] | undefined): number {
  const v = Number(Array.isArray(raw) ? raw[0] : raw);
  if (!Number.isFinite(v) || v <= 0) return 0;
  // حدٌّ أعلى معقول: حافّة أعرض من ٢٠٠ بكسل رقمٌ مكتوب خطأً لا قياس
  return Math.min(Math.round(v), 200);
}

/**
 * ساعة العرض: تُقرأ من `?t=` إن وُجدت، وإلا فالآن.
 *
 * `?t=` للتصوير والاختبار وحده — تُجمّد اللوحة عند لحظةٍ بعينها فأستطيع
 * التقاط الشاشات الأربع في اللحظة نفسها وإلصاقها للتأكّد أن العنصر العابر
 * يكمل عند الحدّ. بلا هذا لا سبيل إلى إثبات الاتّصال البصري إثباتاً.
 */
export function clockAt(raw: string | string[] | undefined, now: number): number {
  const v = Number(Array.isArray(raw) ? raw[0] : raw);
  return Number.isFinite(v) && v >= 0 ? v : now;
}

/**
 * لحظةُ الخادم.
 *
 * في دالّةٍ مستقلّة لا في جسم الصفحة: `Date.now()` نداءٌ غير صافٍ، وReact 19
 * يرفضه داخل الرندر — وهي القاعدة نفسها التي اضطرّت لوحة التحكّم إلى إخراجه
 * (`dashboard/page.tsx:36-37`). وفائدةٌ ثانية: مصدر الوقت صار قابلاً للاستبدال
 * في الاختبار.
 */
export const nowMs = (): number => Date.now();

