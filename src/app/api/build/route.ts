import { NextResponse } from "next/server";

/**
 * بصمة النسخة العاملة — رقمٌ يتغيّر مع كل نشر.
 *
 * Next يُولّد لكل «إجراء خادم» معرّفاً جديداً عند كل بناء. فصفحةٌ بقيت مفتوحة
 * من قبل النشر تنادي معرّفاً لم يعد موجوداً، فيردّ الخادم بخطأ وتقول الشاشة
 * «تعذّر إتمام الطلب — تأكد من الاتصال». والاتصال سليم، والنسخة قديمة.
 *
 * وقد وقع هذا اليوم على كل طلب: نُشرت الدفعات تباعاً وشاشة الكاشير مفتوحة
 * منذ الصباح، فصار كل بيعٍ يفشل حتى يُحدَّث بالصفحة يدوياً.
 *
 * ولحظةُ بدء العملية تكفي بصمةً: الحاوية تُستبدل مع كل نشر، فيتغيّر الرقم
 * بالضرورة ولا يحتاج شيئاً يُولَّد وقت البناء.
 */
export const dynamic = "force-dynamic";

const STARTED_AT = Date.now();

export function GET() {
  return NextResponse.json(
    { id: STARTED_AT },
    { headers: { "Cache-Control": "no-store, no-cache, must-revalidate, max-age=0" } },
  );
}
