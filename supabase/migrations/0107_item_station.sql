-- محطة للصنف الواحد، تغلب محطة قسمه.
--
-- التوجيه كان بالقسم وحده: الصنف يذهب إلى طابعةٍ لأن قسمه يحمل رقم محطتها.
-- وهذا كافٍ ما دام القسم كلّه يُطبخ في مكانٍ واحد — والبرجر كذلك، والبيتزا.
--
-- لكن المالك طلب خمسة أصناف بعينها على طابعة المطبخ: البونلس وبصل مقرمش وخبز
-- الثوم والويدجز والكرلي. وهي موزّعة على قسمين فيهما ثلاثة وعشرون صنفاً، فنقل
-- القسمين يرسل ثمانية عشر صنفاً لم يطلبها أحد — وكنتاكي ٨ قطع على طابعة
-- البرجر ورقةٌ تُرمى.
--
-- فالمحطة صارت تُقرأ من الصنف أولاً، ومن قسمه إن لم يكن له. وتبقى القاعدة
-- نفسها: **التوجيه بيانات لا كود**، فتحويل صنفٍ آخر غداً صفٌّ يُعدَّل لا نشرة.

alter table public.menu_items
  add column if not exists station_id uuid references public.stations(id) on delete set null;

comment on column public.menu_items.station_id is
  'محطة الطبخ لهذا الصنف وحده. فارغةٌ = يرث محطة قسمه (categories.station_id).';

-- والخمسة إلى المطبخ. بالاسم لا بالرقم: الأرقام تختلف بين قاعدةٍ وأخرى،
-- والأسماء هي ما كتبه المالك.
update public.menu_items
   set station_id = (select id from public.stations where name_en = 'kitchen')
 where name_ar in ('البونلس', 'بصل مقرمش', 'خبز ثوم مع الجبن', 'الويدجز', 'الكرلي');
