-- 0102_customer_source.sql — من أين عرفنا هذا الزبون.
--
-- الدفتر كان يحمل الاسم والرقم ولا يقول من أين جاءا: أمن ورقةٍ كتبها كاشير،
-- أم من مكالمة، أم من رسالة واتساب؟ والفرق يهمّ عند إعادة الاستهداف — من كتب
-- إلينا على واتساب يُراسَل عليه، ومن أملى رقمه على الهاتف لا.
--
-- نصٌّ حرّ لا قائمة: المصادر تتكاثر (توترز، طلباتي، رمز الطاولة) وقيدٌ يمنع
-- إضافة مصدرٍ جديد يعني ترحيلاً لكل قناة. والقيمة تُكتب مرّةً عند الإنشاء
-- ولا تُبدَّل — أوّل بابٍ دخل منه الزبون هو بابه.
alter table public.customers add column if not exists source text;

comment on column public.customers.source is 'من أين جاء الزبون: «بوت واتساب»، «مكالمة»، «كاشير»… يُكتب عند الإنشاء';

-- الموجودون قبل اليوم دخلوا من الكاشير أو المكالمات، لا من البوت
update public.customers set source = 'قبل التسجيل' where source is null;
