-- تحديث الأسعار — ٢٩ أيلول ٢٠٢٦، بقائمة المالك.
--
-- السعر يسكن في مكانين لا غير: `menu_items.price` للصنف، و`item_variants
-- .price_override` لحجمه. وكل ما عداهما مناظر (`menu_public`، `variant_public`،
-- `menu_margins`) يُشتقّ منهما — فالكاشير والمنيو والبوت والجدار والتذاكر
-- تقرأ الرقم نفسه، ويُحدَّث في موضعٍ واحد.
--
-- وحجم «ساندويچ» في أكثر الأصناف بلا تعديل، أي يرث سعر الصنف. وفي بعضها
-- تعديلٌ صريح يساوي السعر نفسه — فيُضبط الاثنان معاً، وإلّا بقي صنفٌ واحد
-- بسعرٍ قديم لأن حجمه يتجاوز الأساس.
--
-- ولا يُمسّ صنفٌ لم يذكره المالك: قائمته هي المدى، والباقي يبقى إلى أن
-- يراجعه في المطعم.
--
-- ويُرفع الترحيل بصوتٍ عالٍ إن لم يجد صنفاً: اسمٌ أخطأتُ في نقله يجب أن
-- يوقف الترحيل كلّه، لا أن يمرّ صامتاً فيبيع المحل بسعر الأمس.

do $$
declare
  r record;
  v_id uuid;
  v_meal_rows int;
begin
  for r in
    select * from (values
      -- ── البركر ── (الاسم في النظام، الساندويچ، الوجبة)
      ('بركر لحم بالجبن',        6000,  8000),
      ('بركر لحم',               5500,  7500),   -- «بركر لحم كلاسيك» بقائمة المالك
      ('ماشروم بركر',            7500,  9500),
      ('بركر سموكي',             6500,  9500),
      ('بركر جيلي',              6500,  8500),
      ('بركر دجاج',              4500,  6500),
      ('دبل برجكر لحم بالجبن',   9500, 11500),   -- «دبل بركر بالجبن» بقائمة المالك
      ('فيلي جيز ستيك',          7000,  9000),

      -- ── الزنجر ──
      ('كلاسيك زنجر',            5000,  7000),
      ('زنجر بوفالو',            5500,  7500),
      ('سموك زنجر',              5500,  7500),
      ('مايتي زنجر',             8000, 10000),
      -- «رول دجاج باربكيو» بقائمة المالك. والوجبة ٧٠٠٠ بقراره: نفس فرق
      -- الوجبة في كل الزنجر (+٢٠٠٠)
      ('رول دجاج',               5000,  7000),

      -- ── الكنتاكي ── (بلا وجبات)
      ('كنتاكي 3 قطع',           8750,  null),
      ('كنتاكي 5 قطع',          13750,  null),
      ('كنتاكي 8 قطع',          21000,  null),
      ('كنتاكي 15 قطعة',        36000,  null),
      ('ستربس 3 قطع',            7000,  null),
      ('أجنحة',                  6500,  null),
      ('البونلس',                4000,  null),
      ('ريزو',                   5000,  null),   -- بلا تغيير، وتُذكر للاكتمال

      -- ── الفرايز ── (بلا وجبات)
      ('الويدجز',                3000,  null),
      ('الكرلي',                 3500,  null),
      ('فنكر بالجبن',            4000,  null),   -- بلا تغيير
      ('فنكر صوص',               4000,  null),   -- بلا تغيير
      ('جكن فرايز',              5500,  null),
      ('شيتو جكن فرايز',         6500,  null),
      ('بصل مقرمش',              3500,  null),
      ('خبز ثوم مع الجبن',       4000,  null)
    ) as t(name, single, meal)
  loop
    select id into v_id from public.menu_items where name_ar = r.name and is_active;
    if v_id is null then
      raise exception 'صنف غير موجود أو مطفأ: %', r.name;
    end if;

    update public.menu_items set price = r.single where id = v_id;

    -- حجمٌ باسم الساندويچ بتعديلٍ صريح: يُساوى بالأساس. وبلا تعديل يرثه وحده.
    -- (الإملاءان موجودان في القاعدة: بالچ وبالج)
    update public.item_variants
       set price_override = r.single
     where item_id = v_id
       and price_override is not null
       and name_ar in ('ساندويچ', 'ساندويج');

    if r.meal is not null then
      update public.item_variants
         set price_override = r.meal
       where item_id = v_id and name_ar = 'وجبة';
      get diagnostics v_meal_rows = row_count;
      if v_meal_rows = 0 then
        raise exception 'لا حجم «وجبة» للصنف: %', r.name;
      end if;
    end if;
  end loop;
end $$;
