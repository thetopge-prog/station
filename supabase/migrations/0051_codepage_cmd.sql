-- 0051 — رقم صفحة الترميز لكل طابعة.
--
-- أول فاتورة حقيقية في المحل خرجت بالصينية: الأرقام و QR والتنسيق كلها سليمة،
-- والعربية وحدها تُقرأ حرفين اثنين معاً. هذه الطابعات مصنوعة للسوق الصيني
-- وتبدأ في وضع GB18030، فكل بايت فوق 0x7F هو نصف حرف صيني عندها.
--
-- إلغاء الوضع الصيني (FS .) يُرسل الآن مع كل تذكرة. لكن أي رقم يختار «العربية»
-- بعده يختلف بين طابعة وأخرى — 22 و26 و32 و37 و41 كلها CP864 أو CP1256 على
-- طراز أو آخر، ولا ورقة مواصفات في المحل تقول أيّها. فورقة الاختبار تطبع سطراً
-- عربياً تحت كل رقم، وصاحب المحل يقرأ الورقة ويحفظ الرقم هنا.
alter table public.printers
  add column if not exists codepage_cmd int;

comment on column public.printers.codepage_cmd is
  'رقم ESC t n الذي تعرض به هذه الطابعة العربية — يُقرأ من ورقة الاختبار.';
