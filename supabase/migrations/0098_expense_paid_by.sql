-- مصروف دفعته الإدارة من خارج الدرج.
--
-- المصروف اليوم يعني «نقد خرج من درج الكاشير»، فيُطرح من النقد المتوقَّع في
-- جرد الوردية واليوم. لكن الإدارة تدفع أحياناً من جيبها أو بتحويل إلى مورّد:
-- الكلفة كلفة اليوم فعلاً وتُطرح من الربح، غير أن الدرج لم يمسّه شيء — وطرحها
-- منه كان يصنع عجزاً وهمياً بحجم المبلغ.
--
-- paid_by فارغ = من الدرج كما كان دائماً. وفيه اسم = من خارجه.
alter table public.expenses add column if not exists paid_by text;

comment on column public.expenses.paid_by is
  'اسم من دفع المبلغ من خارج درج الكاشير (إدارة/مالك). NULL = خرج من الدرج.';
