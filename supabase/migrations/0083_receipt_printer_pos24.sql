-- ═══ وصل الزبون على طابعة الكاشير POS-24 ═══
--
-- طابعة الكاشير الفعلية اسمها في ويندوز POS-24، وعليها تخرج تذكرة التجهيز
-- فعلاً. وصل الزبون كان موجّهاً إلى POS80 فلا يخرج معها. المالك يريد الورقتين
-- من الطابعة نفسها: الوصل ثم تذكرة التجهيز بالباركود.
--
-- إعداد لا كود — لكنه في ترحيل ليُطبَّق بنفس طريق كل تغيير على قاعدة المحل.

update public.printers
   set share = 'POS-24', updated_at = now()
 where kind = 'receipt' and is_active and share = 'POS80';
