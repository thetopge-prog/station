-- ═══ رجوع: وصل الزبون إلى POS80 ═══
--
-- 0083 حوّل وصل الزبون إلى POS-24 على قول إنها طابعة الكاشير. فتوقّفت الطباعة
-- عند الكاشير فوراً: الوكيل يسلّم إلى ويندوز باسم الطابعة ويقول «طُبع» لأن
-- الطابور قبل الورقة، لكنّ POS-24 ليست الطابعة التي على الكاونتر. الاسم الذي
-- كان يطبع فعلاً هو POS80 — يعود كما كان. اسم الطابعة الصحيح يُحسم من
-- /printers ← «اطبع الأرقام»، لا من التخمين.

update public.printers
   set share = 'POS80', updated_at = now()
 where kind = 'receipt' and is_active and share = 'POS-24';
