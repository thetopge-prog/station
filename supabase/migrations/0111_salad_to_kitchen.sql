-- «سلطة دايت» إلى طابعة المطبخ — سادس صنفٍ يخرج عن محطة قسمه.
--
-- قسمها «كنتاكي» وهو على الكاونتر، وهي تُحضَّر في المطبخ. ونفس الباب الذي
-- فُتح في 0107 لخمسة أصناف: المحطة تُقرأ من الصنف أولاً ومن قسمه إن لم يكن
-- له — فلا يُنقل القسم كلّه ولا يُكتب سطرُ شيفرة، صفٌّ واحد يُعدَّل.
--
-- وقُرئت حالتها قبل التعديل: بلا محطة خاصّة، ترث الكاونتر. والوردية مقفلة
-- حين طُبِّق، فلا طلبٌ مفتوح يتغيّر مسار ورقته تحت يد المجهّز.

update public.menu_items
   set station_id = (select id from public.stations where name_en = 'kitchen')
 where name_ar = 'سلطة دايت'
   and is_active;
